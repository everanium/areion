// areionRC4x holds the 15 round constants of P1 in pre-broadcast form
// (each 16-byte constant replicated 4 times across a 64-byte ZMM block).
// Layout: round r occupies bytes [r*64 : (r+1)*64].
var areionRC4x [15 * 64]byte

// areionRC4x2 holds the 15 round constants of P2 in pre-broadcast form,
// matching the layout of areionRC4x.
var areionRC4x2 [15 * 64]byte

func init() {
	_ = rijndael256Consts
	_ = vistrutahRoundConstants
	_ = vistrutahConsts
	for r := 0; r < 15; r++ {
		for copyIdx := 0; copyIdx < 4; copyIdx++ {
			copy(areionRC4x[r*64+copyIdx*16:r*64+copyIdx*16+16], roundConstantsP1[r][:])
			copy(areionRC4x2[r*64+copyIdx*16:r*64+copyIdx*16+16], roundConstantsP2[r][:])
		}
	}
}

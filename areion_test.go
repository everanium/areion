func rotateWords256(in [32]byte, byteShift int) (out [32]byte) {
	for i := 0; i < 32; i++ {
		out[i] = in[(i+byteShift)&31]
	}
	return out
}

func rotateWords512(in [64]byte, byteShift int) (out [64]byte) {
	for i := 0; i < 64; i++ {
		out[i] = in[(i+byteShift)&63]
	}
	return out
}


	if hasAESNI {
		tiers = append(tiers, "aesni")
	}
	if hasVAESAVX2 {
		tiers = append(tiers, "vaesavx2")
	}
	if hasAVX512 {
		tiers = append(tiers, "avx512")
	}
	if hasARMCrypto {
		tiers = append(tiers, "arm64")
	}

	var m256 [32]byte
	var key256 [64]byte
	var m512 [64]byte
	var key512 [128]byte
	rand.Read(m256[:])
	rand.Read(key256[:])
	rand.Read(m512[:])
	rand.Read(key512[:])

	var states256x4 [4][32]byte
	var states512x4 [4][64]byte
	var keys256x4 [4][64]byte
	var keys512x4 [4][128]byte
	for i := 0; i < 4; i++ {
		rand.Read(states256x4[i][:])
		rand.Read(states512x4[i][:])
		rand.Read(keys256x4[i][:])
		rand.Read(keys512x4[i][:])
	}

	origTier := Tier()
	defer func() {
		_ = SetTier(origTier)
	}()

	// Baseline under purego
	if err := SetTier("purego"); err != nil {
		t.Fatalf("SetTier(purego) failed: %v", err)
	}
	baseP256 := m256
	Permute256(&baseP256)
	baseP256P2 := m256
	Permute256P2(&baseP256P2)
	baseInv256 := baseP256
	InversePermute256(&baseInv256)

	baseP512 := m512
	Permute512(&baseP512)
	baseP512P2 := m512
	Permute512P2(&baseP512P2)
	baseInv512 := baseP512

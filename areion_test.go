// TestInversePermuteP2Roundtrip checks P2⁻¹(P2(x)) = x and P2(P2⁻¹(x)) = x on every tier,
// and that P2⁻¹ differs from P1⁻¹.
func TestInversePermuteP2Roundtrip(t *testing.T) {
	eachTier(t, func(t *testing.T, tier string) {
		for trial := 0; trial < 100; trial++ {
			var x256 State256
			var x512 State512
			rand.Read(x256[:])
			rand.Read(x512[:])

			s := x256
			Permute256P2(&s)
			InversePermute256P2(&s)
			if s != x256 {
				t.Fatalf("Areion-256 P2 forward-inverse roundtrip failed (tier %s, trial %d)", tier, trial)
			}
			s = x256
			InversePermute256P2(&s)
			Permute256P2(&s)
			if s != x256 {
				t.Fatalf("Areion-256 P2 inverse-forward roundtrip failed (tier %s, trial %d)", tier, trial)
			}
			a, b := x256, x256
			InversePermute256(&a)
			InversePermute256P2(&b)
			if a == b {
				t.Fatalf("InversePermute256P2 equals InversePermute256 (tier %s)", tier)
			}

			u := x512
			Permute512P2(&u)
			InversePermute512P2(&u)
			if u != x512 {
				t.Fatalf("Areion-512 P2 forward-inverse roundtrip failed (tier %s, trial %d)", tier, trial)
			}
			u = x512
			InversePermute512P2(&u)
			Permute512P2(&u)
			if u != x512 {
				t.Fatalf("Areion-512 P2 inverse-forward roundtrip failed (tier %s, trial %d)", tier, trial)
			}
			c, d := x512, x512
			InversePermute512(&c)
			InversePermute512P2(&d)
			if c == d {
				t.Fatalf("InversePermute512P2 equals InversePermute512 (tier %s)", tier)
			}
		}
	})
}

func TestDaviesMeyer(t *testing.T) {
	// DM256: h = P1(m) ⊕ m
	var m256 [32]byte
	rand.Read(m256[:])
	h256 := DM256(&m256)

	p256 := m256
	Permute256(&p256)
	for i := range p256 {
		p256[i] ^= m256[i]
	}
	if !bytes.Equal(h256[:], p256[:]) {
		t.Fatalf("DM256 mismatch\nGot:  %x\nWant: %x", h256[:], p256[:])
	}

	// DM512: h = Trunc256(P1(m) ⊕ m)
	var m512 [64]byte
	rand.Read(m512[:])
	h512 := DM512(&m512)

	p512 := m512
	Permute512(&p512)
	for i := range p512 {
		p512[i] ^= m512[i]
	}
	var expected512 [32]byte
	copy(expected512[0:8], p512[8:16])
	copy(expected512[8:16], p512[24:32])
	copy(expected512[16:24], p512[32:40])
	copy(expected512[24:32], p512[48:56])

	if !bytes.Equal(h512[:], expected512[:]) {
		t.Fatalf("DM512 mismatch\nGot:  %x\nWant: %x", h512[:], expected512[:])
	}
}


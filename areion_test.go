// TestEdgeCases tests edge case states: all zeros, all ones, Hamming weight 1,
// Hamming weight n-1, and alternating bit patterns 0x55, 0xAA.
func TestEdgeCases(t *testing.T) {
	var edge256 []State256
	var edge512 []State512

	var z256 State256
	var z512 State512
	edge256 = append(edge256, z256)
	edge512 = append(edge512, z512)

	var o256 State256
	var o512 State512
	for i := range o256 {
		o256[i] = 0xff
	}
	for i := range o512 {
		o512[i] = 0xff
	}
	edge256 = append(edge256, o256)
	edge512 = append(edge512, o512)

	var a55_256, aAA_256 State256
	var a55_512, aAA_512 State512
	for i := range a55_256 {
		a55_256[i] = 0x55
		aAA_256[i] = 0xaa
	}
	for i := range a55_512 {
		a55_512[i] = 0x55
		aAA_512[i] = 0xaa
	}
	edge256 = append(edge256, a55_256, aAA_256)
	edge512 = append(edge512, a55_512, aAA_512)

	for byteIdx := 0; byteIdx < 32; byteIdx++ {
		for bitIdx := 0; bitIdx < 8; bitIdx++ {
			var s State256
			s[byteIdx] = 1 << bitIdx
			edge256 = append(edge256, s)
			sClear := o256
			sClear[byteIdx] ^= 1 << bitIdx
			edge256 = append(edge256, sClear)
		}
	}
	for byteIdx := 0; byteIdx < 64; byteIdx++ {
		for bitIdx := 0; bitIdx < 8; bitIdx++ {
			var s State512
			s[byteIdx] = 1 << bitIdx
			edge512 = append(edge512, s)
			sClear := o512
			sClear[byteIdx] ^= 1 << bitIdx
			edge512 = append(edge512, sClear)
		}
	}

	t.Run("Permute256 Invertibility on Edge Cases", func(t *testing.T) {
		for i, s := range edge256 {
			fwd := s
			Permute256(&fwd)
			inv := fwd
			InversePermute256(&inv)
			if !bytes.Equal(inv[:], s[:]) {
				t.Fatalf("Permute256 edge case %d failed inversion", i)
			}
		}
	})

	t.Run("Permute512 Invertibility on Edge Cases", func(t *testing.T) {
		for i, s := range edge512 {
			fwd := s
			Permute512(&fwd)
			inv := fwd
			InversePermute512(&inv)
			if !bytes.Equal(inv[:], s[:]) {
				t.Fatalf("Permute512 edge case %d failed inversion", i)
			}
		}
	})

	t.Run("DM256 and DM512 Non-Zero on Edge Cases", func(t *testing.T) {
		var z32 [32]byte
		for i, s := range edge256 {
			d := DM256(&s)
			if bytes.Equal(d[:], z32[:]) {
				t.Fatalf("DM256 edge case %d produced zero digest", i)
			}
		}
		for i, s := range edge512 {
			d := DM512(&s)
			if bytes.Equal(d[:], z32[:]) {
				t.Fatalf("DM512 edge case %d produced zero digest", i)
			}
		}
	})
}

// TestAvalancheStrict measures avalanche effect: flipping 1 input bit flips ~n/2 output bits.
func TestAvalancheStrict(t *testing.T) {
	t.Run("Permute256 Avalanche", func(t *testing.T) {
		var base State256
		rand.Read(base[:])
		pBase := base
		Permute256(&pBase)

		totalFlips := 0
		tests := 0

		for byteIdx := 0; byteIdx < 32; byteIdx++ {
			for bitIdx := 0; bitIdx < 8; bitIdx++ {
				mut := base
				mut[byteIdx] ^= 1 << bitIdx
				pMut := mut
				Permute256(&pMut)

				diffBits := 0
				for i := 0; i < 32; i++ {
					diffBits += bits.OnesCount8(pBase[i] ^ pMut[i])
				}
				totalFlips += diffBits
				tests++
			}
		}
		avgFlips := float64(totalFlips) / float64(tests)
		if avgFlips < 100 || avgFlips > 156 {
			t.Fatalf("Permute256 failed avalanche criterion: avg=%.2f", avgFlips)
		}
	})

	t.Run("Permute512 Avalanche", func(t *testing.T) {
		var base State512
		rand.Read(base[:])
		pBase := base
		Permute512(&pBase)

		totalFlips := 0
		tests := 0

		for byteIdx := 0; byteIdx < 64; byteIdx++ {
			for bitIdx := 0; bitIdx < 8; bitIdx++ {
				mut := base
				mut[byteIdx] ^= 1 << bitIdx
				pMut := mut
				Permute512(&pMut)

				diffBits := 0
				for i := 0; i < 64; i++ {
					diffBits += bits.OnesCount8(pBase[i] ^ pMut[i])
				}
				totalFlips += diffBits
				tests++
			}
		}
		avgFlips := float64(totalFlips) / float64(tests)
		if avgFlips < 200 || avgFlips > 312 {
			t.Fatalf("Permute512 failed avalanche criterion: avg=%.2f", avgFlips)
		}
	})
}


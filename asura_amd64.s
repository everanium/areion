	PXOR X2, X6
	MOVOA X1, X7
	PXOR X2, X7
	MOVOU X6, 0(AX)
	MOVOU X7, 16(AX)

	PXOR X0, X0
	PXOR X1, X1
	PXOR X2, X2
	PXOR X3, X3
	PXOR X4, X4
	PXOR X5, X5
	PXOR X6, X6
	PXOR X7, X7
	XORQ AX, AX
	XORQ BX, BX
	XORQ CX, CX
	XORQ DX, DX

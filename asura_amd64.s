	VMOVDQA T0, K0 \
	VPCMPGTB K0, ZERO, T0 \
	VPCMPGTB K1, ZERO, T1 \
	VPAND POLY1B, T0, T0 \
	VPAND POLY1B, T1, T1 \
	VPADDB K0, K0, K0 \
	VPADDB K1, K1, K1 \
	VPXOR T0, K0, K0 \
	VPXOR T1, K1, K1 \
	VPSHUFB PITAU, K0, K0 \
	VPSHUFB PITAU, K1, K1


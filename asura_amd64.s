#define ASURA_KAPPA_SSE(K0, K1, PITAU, POLY1B, ZERO, T0, T1) \
	MOVOA K0, T0 \
	PBLENDW $0xcc, K1, K0 \
	PBLENDW $0xcc, T0, K1 \
	MOVOA ZERO, T0 \
	MOVOA ZERO, T1 \
	PCMPGTB K0, T0 \
	PCMPGTB K1, T1 \
	PAND POLY1B, T0 \
	PAND POLY1B, T1 \
	PADDB K0, K0 \
	PADDB K1, K1 \
	PXOR T0, K0 \
	PXOR T1, K1 \
	PSHUFB PITAU, K0 \
	PSHUFB PITAU, K1

#define ASURA_KAPPA_VEX(K0, K1, PITAU, POLY1B, ZERO, T0, T1) \

	PXOR T1, K0 \
	MOVOA K1, T0 \
	PSLLW $7, T0 \
	MOVOA ZERO, T1 \
	PCMPGTB T0, T1 \
	PAND POLY8D, T1 \
	PSRLW $1, K1 \
	PAND MASK7F, K1 \
	PXOR T1, K1 \
	PSHUFB PITAU_INV, K0 \
	PSHUFB PITAU_INV, K1 \
